"""Estate B - "legacy ETL": the Hive -> Snowflake traps, each with a known right answer.

Categories (the metrics reward getting the category right):
- convertible:      a faithful Snowflake version exists; the result must match the source;
- unconvertible:    the information needed is not in the SQL (a UDF from a jar or the metastore
                    whose source is unknown, a TRANSFORM script): the right output is a hand-back
                    that names the construct and suggests the fix. Engine-specific hashes and
                    reflect() on JDK methods are *convertible*: a UDF reproduces them and the data
                    proves it (v1 did exactly that for hash(), which overturned the first label);
- needs_config:     convertible only with environment mapping a person must supply (HDFS /
                    S3 paths -> stages, external table locations): hand back with the mapping
                    needed;
- maskable:         deterministic except for audit columns that are clock values (load_ts) -
                    convert, and verify with those columns masked;
- nondeterministic: the result is not fixed by the query (random, undefined order, sampling,
                    ties, approximate functions): a match is luck; hand back as unverifiable.

Spark 3.5 is the source engine. Objects whose Hive-vs-Spark semantics differ are tagged
`spark3_semantics`: the truth is Spark 3's behaviour and the report says so.
"""

